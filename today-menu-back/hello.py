# ============================================================
# hello.py
# OpenAI API에 첫 메시지를 보내고 응답을 받는 가장 간단한 예제
# ============================================================

# ────────────────────────────────────────────────────────────
# [1] 필요한 라이브러리(도구) 불러오기
# ────────────────────────────────────────────────────────────
from openai import OpenAI        # OpenAI 공식 SDK (AI와 통신용)
from dotenv import load_dotenv   # .env 파일을 읽어주는 도구

# ────────────────────────────────────────────────────────────
# [2] .env 파일에 적힌 환경변수를 시스템에 등록
#     이 한 줄 덕분에 .env의 OPENAI_API_KEY가 자동으로 인식됨
# ────────────────────────────────────────────────────────────
load_dotenv()

# ────────────────────────────────────────────────────────────
# [3] OpenAI 클라이언트 객체 생성
#     api_key를 코드에 직접 안 넣어도, 위에서 등록한
#     환경변수(OPENAI_API_KEY)를 자동으로 찾아서 사용함
#     ↳ 이게 우리가 .env 파일을 만든 이유!
# ────────────────────────────────────────────────────────────
client = OpenAI()

# ────────────────────────────────────────────────────────────
# [4] AI한테 메시지 보내고 응답 받기 (API 호출!)
# ────────────────────────────────────────────────────────────
response = client.chat.completions.create(
    # 어떤 AI 모델을 쓸지 선택 (gpt-4o-mini = 저렴하고 빠름)
    model="gpt-4o-mini",
    
    # 대화 내용을 리스트로 전달
    messages=[
        # role: "system" → AI의 역할/성격을 미리 정해주는 지시문
        {
            "role": "system",
            "content": "너는 친절한 한국어 어시스턴트야. 짧고 다정하게 답해."
        },
        # role: "user" → 실제 사용자가 묻는 메시지
        {
            "role": "user",
            "content": "안녕! 너는 누구야? 한 줄로 자기소개 해줘."
        }
    ]
)

# ────────────────────────────────────────────────────────────
# [5] 응답에서 실제 답변 텍스트만 꺼내서 출력
#     response 안에는 토큰 사용량, 응답 ID 등 여러 정보가 들어있음
#     그 중 답변 내용(.choices[0].message.content)만 추출
# ────────────────────────────────────────────────────────────
answer = response.choices[0].message.content

print("=" * 50)
print("🤖 AI 답변:", answer)
print("=" * 50)