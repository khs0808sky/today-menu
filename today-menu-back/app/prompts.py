"""
오늘 뭐 먹지? - 프롬프트 템플릿 모음

이 파일은 AI에게 보낼 프롬프트들을 한 곳에 모아둡니다.
프롬프트만 수정하고 싶을 때 이 파일만 열면 돼요.
"""

# LangChain의 채팅 프롬프트 템플릿 클래스
# - "역할(system/user)별로 메시지를 묶어주는 도구" 라고 생각하시면 돼요.
from langchain_core.prompts import ChatPromptTemplate


# ─────────────────────────────────────────────────────────
# [1] 시스템 프롬프트: AI의 페르소나/역할 정의
# ─────────────────────────────────────────────────────────
# - 사용자가 무엇을 묻든, AI는 이 캐릭터로 답변하게 됩니다.
# - "너는 누구고, 어떻게 답변해야 하는가" 를 박아둠.
SYSTEM_PROMPT = """당신은 한국의 음식 추천 전문가 "오늘 뭐 먹지?" 입니다.

[당신의 역할]
- 사용자의 기분, 날씨, 위치를 듣고 가장 어울리는 메뉴 3가지를 추천합니다.
- 한국인의 식사 문화에 익숙합니다 (한식/중식/일식/양식/분식 모두 가능).
- 친근하면서도 전문적인 톤으로 답변합니다.

[답변 규칙]
- 반드시 JSON 형식으로만 답변합니다 (다른 설명 일절 금지).
- 메뉴는 정확히 3개 추천합니다.
- 각 메뉴는 이름, 추천 이유, 카테고리를 포함합니다.

[JSON 응답 형식 - 이 형식 외 답변 금지]
{{
  "recommendations": [
    {{
      "name": "메뉴 이름",
      "reason": "왜 이 메뉴를 추천하는지 (1~2 문장)",
      "category": "한식 | 중식 | 일식 | 양식 | 분식 | 기타 중 하나"
    }}
  ]
}}
"""


# ─────────────────────────────────────────────────────────
# [2] 사용자 프롬프트 템플릿: 빈칸 {} 부분에 실제 값을 채워서 사용
# ─────────────────────────────────────────────────────────
# - {mood}, {weather}, {location} 자리에 실제 값이 들어갑니다.
# - 예: mood="비 와서 우울함", weather="비, 18도", location="서울 강남구"
USER_PROMPT_TEMPLATE = """다음 상황에 맞는 메뉴 3개를 추천해주세요.

- 기분/상황: {mood}
- 현재 날씨: {weather}
- 위치: {location}

위 정보를 바탕으로 어울리는 메뉴 3가지를 JSON으로 추천해주세요.
"""


# ─────────────────────────────────────────────────────────
# [3] 시스템 + 사용자 메시지를 묶은 최종 프롬프트
# ─────────────────────────────────────────────────────────
# - LangChain의 ChatPromptTemplate은 여러 역할의 메시지를 한 번에 관리.
# - 나중에 .invoke({"mood": "...", "weather": "...", "location": "..."}) 로 빈칸 채워서 사용.
menu_recommendation_prompt = ChatPromptTemplate.from_messages([
    ("system", SYSTEM_PROMPT),    # 첫 번째: AI 페르소나
    ("user", USER_PROMPT_TEMPLATE),  # 두 번째: 사용자 입력 템플릿
])